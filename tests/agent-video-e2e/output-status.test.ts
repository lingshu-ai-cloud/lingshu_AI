async function persistedOutput() {
  const x = await outputFixture();
  const result = await x.port(x.input);
  const repository = createStarter198Repository(x.f.store);
  const run = x.f.tables.workflow_runs!.find(row => row.id === x.input.job.runId)!;
  const receipt = {operationId: x.input.intent.operationId, jobId: x.input.job.id,
    executionRunId: x.input.job.runId, ...result};
  run.starter_context = {...run.starter_context as object, sceneReworkOutput: {...receipt, recordHash: socialRequestHash(receipt)}};
  const read = () => readSocialSceneReworkStatus({repository, tenantId: 't', taskId: 'content',
    actorUserId: 'owner', operationId: x.input.intent.operationId});
  return {x, result, repository, run, read};
}

test('actual OutputPort artifact projects exact non-null output and completion times without mutation', async () => {
  const p = await persistedOutput();
  try {
    const job = p.x.f.tables.content_execution_jobs![0]!;
    job.status = 'succeeded'; job.completed_at = '2026-10-10T01:00:00.000Z';
    p.run.status = 'completed'; p.run.completed_at = '2026-10-10T01:00:01.000Z';
    const before = JSON.stringify(p.x.f.tables);
    const status = await p.read();
    assert.deepEqual(status.output, {...p.result, savedAt: p.x.f.tables.starter_social_content_artifacts!.find(row => row.artifact_id === p.result.artifactId)!.created_at});
    assert.equal(status.completedAt, job.completed_at);
    assert.equal(status.runCompletedAt, p.run.completed_at);
    assert.equal(status.output!.reviewStatus, 'review_required');
    assert.equal(status.output!.qualityReceiptIds.length, p.x.f.context.cache.scenes.length);
    assert.equal(p.x.f.tables.starter_social_content_tasks![0]!.run_id, 'run');
    assert.equal(JSON.stringify(p.x.f.tables), before);
    const cache = await p.x.f.service.readCache({tenantId: 't', taskId: 'content', runId: 'rework-run', parentArtifactId: p.result.artifactId});
    assert.ok(cache.cache.scenes.every(scene => scene.status === 'review_required'));
  } finally {await p.x.f.cleanup();}
});

test('read rejects recomputed artifact lineage, SHA and incomplete G4 output evidence', async () => {
  const p = await persistedOutput();
  try {
    const row = p.x.f.tables.starter_social_content_artifacts!.find(row => row.artifact_id === p.result.artifactId)!;
    const original = structuredClone(row.content) as any;
    const rehash = () => {row.content_hash = socialRequestHash({resourceRef: row.resource_ref, content: row.content});};
    (row.content as any).sceneRework.operationHash = 'f'.repeat(64); rehash();
    await assert.rejects(p.read(), /source_intent_invalid/);
    row.content = structuredClone(original);
    (row.content as any).mediaStorage.video.sha256 = 'f'.repeat(64); rehash();
    await assert.rejects(p.read(), /output_receipt_invalid/);
    row.content = structuredClone(original); rehash();
    const saved = (p.run.starter_context as any).sceneReworkOutput;
    saved.qualityReceiptIds = saved.qualityReceiptIds.slice(0, 1);
    const {recordHash, ...receipt} = saved; void recordHash;
    saved.recordHash = socialRequestHash(receipt);
    await assert.rejects(p.read(), /output_quality_incomplete/);
  } finally {await p.x.f.cleanup();}
});

test('completion write interruption preserves actual output and direct retry finalizes idempotently', async () => {
  const p = await persistedOutput();
  try {
    // Keep the actual generated bytes accessible through the default local file port.
    const file = p.x.f.tables.starter_social_content_files!.find(row => `socialfile:${row.file_id}` === p.result.fileRef)!;
    const local = path.join(path.dirname(p.x.f.local), `${p.result.sha256}.mp4`);
    await copyFile(p.x.input.outputPath, local);
    Object.assign(file, {storage_kind: 'local', storage_key: path.relative(path.resolve('data/social-content-sources'), local)});
    const job = p.x.f.tables.content_execution_jobs![0]!;
    job.status = 'succeeded'; job.completed_at = '2026-10-10T01:00:00.000Z';
    const sourceBefore = JSON.stringify(p.x.f.tables.workflow_runs!.find(row => row.id === 'run'));
    const artifactCount = p.x.f.tables.starter_social_content_artifacts!.length;
    const update = p.x.f.store.update.bind(p.x.f.store);
    let interrupted = false;
    p.x.f.store.update = async (collection, id, data) => {
      if (collection === 'workflow_runs' && id === 'rework-run' && data.status === 'completed' && !interrupted) {
        interrupted = true; return false;
      }
      return update(collection, id, data);
    };
    await assert.rejects(completeSocialSceneReworkRun(p.repository, p.x.input.job), /completion_save_failed/);
    assert.equal(job.status, 'succeeded'); assert.equal(p.run.status, 'running');
    await completeSocialSceneReworkRun(p.repository, p.x.input.job);
    const completedAt = p.run.completed_at;
    await completeSocialSceneReworkRun(p.repository, p.x.input.job);
    assert.equal(p.run.status, 'completed'); assert.equal(p.run.completed_at, completedAt);
    assert.equal(p.x.f.tables.starter_social_content_artifacts!.length, artifactCount);
    assert.equal(JSON.stringify(p.x.f.tables.workflow_runs!.find(row => row.id === 'run')), sourceBefore);
    assert.equal((await p.read()).output!.artifactId, p.result.artifactId);
  } finally {await p.x.f.cleanup();}
});

test('durable worker callback failure must preserve succeeded output job for completion-only recovery', async () => {
  const p = await persistedOutput();
  let executions = 0, callbacks = 0;
  const worker = new DurableContentExecutionWorker({dataStore: p.x.f.store,
    env: {CONTENT_EXECUTION_WORKER_CONCURRENCY: '1', CONTENT_EXECUTION_LEASE_MS: '60000'},
    execute: async () => {executions++; assert.equal((await p.read()).output!.artifactId, p.result.artifactId);},
    onSucceeded: async () => {callbacks++; throw new Error('scene_rework_run_completion_save_failed');}});
  try {
    const job = p.x.f.tables.content_execution_jobs![0]!;
    Object.assign(job, {status: 'queued', worker_id: '', lease_expires_at: '', next_attempt_at: '', attempt: 0});
    p.x.f.tables.durable_operation_leases = p.x.f.tables.durable_operation_leases!.filter(row => row.id !== 'live');
    await worker.drain();
    for (let i = 0; i < 100 && (!callbacks || worker.isLocallyActive('t', 'content')); i++) {
      await new Promise(resolve => setTimeout(resolve, 10));
    }
    assert.equal(executions, 1); assert.equal(callbacks, 1);
    assert.equal(job.status, 'succeeded', 'post-success completion failure must not downgrade a finished media job');
    assert.ok(job.completed_at); assert.equal(p.run.status, 'running');
    assert.equal((await p.read()).output!.artifactId, p.result.artifactId);
  } finally {worker.stop(); await p.x.f.cleanup();}
});

test('completion scanner recovers actual OutputPort media once without execution or new output', async () => {
  const p = await persistedOutput();
  try {
    const file = p.x.f.tables.starter_social_content_files!.find(row => `socialfile:${row.file_id}` === p.result.fileRef)!;
    const local = path.join(path.dirname(p.x.f.local), `${p.result.sha256}.mp4`);
    await copyFile(p.x.input.outputPath, local);
    Object.assign(file, {storage_kind: 'local', storage_key: path.relative(path.resolve('data/social-content-sources'), local)});
    Object.assign(p.x.f.tables.content_execution_jobs![0]!, {status: 'succeeded', completed_at: '2026-10-10T01:00:00.000Z'});
    const counts = ['starter_social_content_artifacts', 'starter_social_content_files', 'starter_social_production_receipts', 'content_execution_jobs'].map(c => p.x.f.tables[c]!.length);
    const first = await recoverSocialSceneReworkCompletions({repository: p.repository});
    assert.equal(first.recovered, 1); assert.equal(first.failed, 0);
    const completedAt = p.run.completed_at;
    const second = await recoverSocialSceneReworkCompletions({repository: p.repository});
    assert.equal(second.recovered, 0); assert.equal(second.failed, 0); assert.equal(second.skipped, 1);
    assert.equal(p.run.completed_at, completedAt);
    assert.deepEqual(['starter_social_content_artifacts', 'starter_social_content_files', 'starter_social_production_receipts', 'content_execution_jobs'].map(c => p.x.f.tables[c]!.length), counts);
    assert.equal((await p.read()).output!.artifactId, p.result.artifactId);
  } finally {await p.x.f.cleanup();}
});

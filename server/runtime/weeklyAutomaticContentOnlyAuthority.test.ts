import assert from 'node:assert/strict';
import test from 'node:test';
import {prepareWeeklyNonPresenterPlanningFixture} from './weeklyNonPresenterProduction.fixture.js';
import {createWeeklyPlanningAuthority} from '../socialPrograms/planningAuthority.js';
import {buildWeeklyProductionPlanningAuthority,persistWeeklyProductionPlanningAuthority} from '../socialPrograms/weeklyProductionPlanningAuthority.js';
import {readWeeklyExistingFactSource} from '../socialPrograms/weeklyExistingFactSource.js';
import {WEEKLY_AUTOMATIC_PRODUCTION_INTENTS,readWeeklyAutomaticProductionIntent,type WeeklyAutomaticProductionIntent} from '../socialPrograms/weeklyAutomaticProductionPlanning.js';
import {socialRequestHash} from '../starter198/socialContentValidation.js';
import {createSocialWeeklyProductionAdapter} from './socialWeeklyProductionAdapter.js';
import {createSocialWeeklyPlanningAdapter} from './socialWeeklyExecutionRuntime.js';
import {validateWeeklyExecutionResults} from './socialWeeklyResultValidation.js';
import type {WeeklyExecutionTask} from '../../shared/contracts/socialProgram.js';
import type {BusinessContentGoal} from '../../shared/contracts/socialOperatingDecision.js';

test('accepted template keeps blocked conversion goal unchanged and refuses production without its real capacity proof',async t=>{
 const {f,pkg}=await prepareWeeklyNonPresenterPlanningFixture(t,{ownedReferenceBytes:true,primaryStructure:true,metricTargets:['真实成片']});
 const planner=createWeeklyPlanningAuthority(f.store),scope={tenantId:'t',programId:'p',packageId:pkg.packageId,packageVersion:pkg.version};
 f.tables.social_weekly_agent_planning=f.tables.social_weekly_agent_planning!.filter(row=>!['confirmed','dispatched'].includes((row.payload as {status:string}).status));
 const before=await planner.get('t','p',pkg.packageId,pkg.version);
 assert.equal(before.status,'awaiting_confirmation');
 const adopted=await planner.confirmAutomaticTemplate({...scope,actorUserId:'owner',expectedPlanningVersion:before.version,selectedSlotIds:before.detailedSchedule!.coverage!.selectedSlotIds});
 const dispatched=await planner.dispatch({...scope,actor:'business_agent',expectedPlanningVersion:adopted.version,selectedSlotIds:adopted.automaticTemplateAdoption!.selectedSlotIds});
 assert.equal(dispatched.userConfirmation,null);
 const goalRow=f.tables.social_business_content_goals!.find(row=>row.goal_id===pkg.businessContentGoalRef!.id)!;
 const goal={...(goalRow.payload as BusinessContentGoal),status:'blocked' as const,conversionRouteIds:[],blockers:[{code:'conversion_route_required' as const,field:'conversionRoutes',message:'No verified route',recoverable:true as const}]};
 goalRow.payload=goal;
 const publication=pkg.socialContentPackage.publicationTasks[0]!;
 const task={...f.task,tenantId:'t',programId:'p',packageId:pkg.packageId,packageVersion:pkg.version,publicationTaskId:publication.publicationTaskId,accountId:publication.accountId,schedule:{...f.task.schedule,stepKind:'material_preparation'}} as WeeklyExecutionTask;
 const adapter=createSocialWeeklyProductionAdapter(f.store,{create:async()=>{throw Error('unverified CTA must not create a content task');},start:async()=>{throw Error('unverified CTA must not start paid production');}});
 const without=await adapter.execute(task);
 assert.equal(without.status,'blocked');
 assert.equal(without.status==='blocked'?without.code:null,'business_dispatch_required');
 const source=await readWeeklyExistingFactSource(f.store,'t');
 const production=buildWeeklyProductionPlanningAuthority({tenantId:'t',pkg,planning:dispatched,goal,factSourceRef:source.ref,factSourceHash:source.sourceHash,now:new Date().toISOString()});
 await persistWeeklyProductionPlanningAuthority(f.store,production);
 const adoption=dispatched.automaticTemplateAdoption!;
 const intentId=socialRequestHash([scope,adoption.recordHash]);
 const intent:WeeklyAutomaticProductionIntent={intentId,scope,source:'automatic_template',templateVersion:'weekly-automation.v3',adoptedAt:production.adoptedAt,userApproval:null,actorUserId:'owner',planningAdoptionHash:adoption.recordHash,productionAuthorityProofId:production.proofId,capacityProofId:'controlled-capacity-missing',dispatchHash:socialRequestHash(dispatched.dispatch),selectedPublicationTaskIds:dispatched.dispatch!.scheduleItems.map(item=>item.publicationTaskId),authorizesPublishing:false,authorizesContentAcceptance:false,authorizesCustomerMessages:false};
 await f.store.create(WEEKLY_AUTOMATIC_PRODUCTION_INTENTS,{id:intentId,tenant_id:'t',program_id:'p',package_id:pkg.packageId,package_version:pkg.version,payload:intent,content_hash:socialRequestHash(intent)});
 const bound=await readWeeklyAutomaticProductionIntent(f.store,scope,pkg,publication.publicationTaskId);
 assert.ok(bound);
 assert.equal(bound.authority.goal.status,'blocked');
 assert.deepEqual(bound.authority.proof.deferredOutboundBlockers,['conversion_route_required']);
 assert.equal(bound.intent.authorizesPublishing,false);
 assert.equal(bound.intent.authorizesContentAcceptance,false);
 assert.equal(bound.intent.authorizesCustomerMessages,false);
 const intentRow=f.tables[WEEKLY_AUTOMATIC_PRODUCTION_INTENTS]!.find(row=>row.id===intentId)!;
 intentRow.tenant_id='another-tenant';
 assert.equal(await readWeeklyAutomaticProductionIntent(f.store,scope,pkg,publication.publicationTaskId),null,'an intent cannot be read through a foreign storage envelope');
 intentRow.tenant_id='t';
 intentRow.package_version=pkg.version+1;
 assert.equal(await readWeeklyAutomaticProductionIntent(f.store,scope,pkg,publication.publicationTaskId),null,'a migrated package cannot inherit the old production opt-in');
 intentRow.package_version=pkg.version;
 const planningTask={...task,workflowKind:'directing' as const,schedule:{...task.schedule,stepKind:'business_schedule' as const},inputSnapshot:{motherContentId:publication.motherContentId}};
 const planningResult=await createSocialWeeklyPlanningAdapter(f.store).execute(planningTask);
 assert.equal(planningResult.status,'succeeded');
 if(planningResult.status==='succeeded')await validateWeeklyExecutionResults(f.store,planningTask,planningResult.resultRefs);
 const result=await adapter.execute(task);
 assert.equal(result.status,'blocked');
 assert.equal(result.status==='blocked'?result.code:null,'weekly_automatic_production_capacity_required');
 assert.equal(f.tables.starter_social_content_tasks?.length??0,0);
 assert.equal(f.tables.content_execution_jobs?.length??0,0);
 assert.equal((goalRow.payload as {status:string}).status,'blocked');
 intentRow.content_hash='tampered';
 const tampered=await adapter.execute(task);
 assert.equal(tampered.status,'blocked');
 assert.equal(tampered.status==='blocked'?tampered.code:null,'business_dispatch_required');
 assert.equal(f.tables.starter_social_content_tasks?.length??0,0);
});

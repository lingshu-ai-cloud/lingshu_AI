import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createHash } from 'node:crypto';
const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'creative-library-'));
process.env.LOCAL_STORE_DIR = temp;
process.env.PB_URL = 'http://127.0.0.1:1';
process.env.NODE_ENV = 'test';
process.env.ENABLE_LOCAL_DEV_FALLBACK = 'true';
process.env.TEST_ONLY_EXTERNAL_EFFECT_LEASE_FALLBACK = 'true';
process.env.META_ADS_API_VERSION = 'v26.0';
process.env.TENANT_PLATFORM_APP_KEY = 'isolated-creative-library-test';
const mediaKey = `creative-library-${process.pid}`;
const mediaDir = path.join(process.cwd(), 'data/social-content-sources', mediaKey);
const originalFetch = globalThis.fetch;
const originalNow = Date.now;
let clockOffset = 0;
Date.now = () => originalNow() + clockOffset;
try {
  const { store } = await import('../storage/index.js');
  const { encryptSecret } = await import('../lib/tenantPlatformApps.js');
  const { createPlatformAdTask, getPlatformAdTask } = await import('./tasks.js');
  const { bindPlatformAdCreative, getPlatformAdCreative } = await import('./creatives.js');
  const { listAdCreativeLibrary, getAdCreativeReport, getAdCreativePreview } = await import('./creativeLibrary.js');
  const { attachExistingAdCreative } = await import('./creativeMapping.js');
  const bytes = Buffer.from('isolated library video');
  const sha256 = createHash('sha256').update(bytes).digest('hex');
  fs.mkdirSync(mediaDir, { recursive: true }); fs.writeFileSync(path.join(mediaDir, `${sha256}.mp4`), bytes);
  await store.create('starter_social_content_files', { id: 'libraryfile0001', tenant_id: 'tenant', task_id: 'source', file_id: 'socialfile_1234567890abcdef12345678', usage: 'artifact_media', byte_size: bytes.length, content_sha256: sha256, name: 'Final.mp4', mime_type: 'video/mp4', storage_kind: 'local', storage_key: `${mediaKey}/${sha256}.mp4` });
  await store.create('starter_social_content_artifacts', { id: 'libraryartifact', tenant_id: 'tenant', task_id: 'source', artifact_id: 'artifact', status: 'approved', origin: 'manual', artifact_kind: 'short_video', resource_ref: 'socialfile:socialfile_1234567890abcdef12345678', version: '1' });
  const input = { name: 'Library', video: 'Final', market: 'US', budget: 100, goal: '提升网站访问', channels: ['Facebook'] };
  const traffic = await createPlatformAdTask('tenant', 'user', input);
  const views = await createPlatformAdTask('tenant', 'user', { ...input, goal: '提升有效视频观看' });
  const account = await store.create<any>('platform_ad_connections', { tenant_id: 'tenant', provider: 'meta', accountId: '1', status: 'connected', currency: 'USD', timezoneName: 'Asia/Shanghai', name: 'Test', tokenCipher: encryptSecret('secret-test-token') });
  const { creative } = await bindPlatformAdCreative('tenant', traffic.id, { expectedVersion: traffic.version, sourceTaskId: 'source', artifactId: 'artifact', connectionId: account.id });
  await store.update('platform_ad_creatives', creative.id, { status: 'ready', platformVideoId: '500', uploadReceipt: { accountId: '1', videoId: '500', sha256, status: 'ready' } });
  await store.update('platform_ad_tasks', traffic.id, { status: 'paused' });
  await store.update('platform_ad_tasks', views.id, { status: 'paused' });
  const receipt = await store.create<any>('platform_ad_executions', { tenant_id: 'tenant', taskId: views.id, connectionId: account.id, action: 'create', status: 'VERIFIED', result: { campaignId: '101', adsetId: '102', creativeId: '103', adId: '104' } });
  let videoId = '500', accountId = '1', status = 'PAUSED', rows: any[] = [];
  const requests: string[] = [];
  globalThis.fetch = (async (url: any, init?: RequestInit) => {
    if (String(url).startsWith('http://127.0.0.1:1/')) return originalFetch(url, init);
    assert.equal(init?.method || 'GET', 'GET', 'library/mapping MUST NOT write to Meta');
    const u = new URL(String(url)); requests.push(u.pathname);
    assert.equal(u.origin, 'https://graph.facebook.com');
    const common = { account_id: accountId, status };
    if (u.pathname.endsWith('/101')) return Response.json({ ...common, id: '101' });
    if (u.pathname.endsWith('/102')) return Response.json({ ...common, id: '102', campaign_id: '101' });
    if (u.pathname.endsWith('/103')) return Response.json({ ...common, id: '103', object_story_spec: { page_id: '600', video_data: { video_id: videoId } } });
    if (u.pathname.endsWith('/104')) return Response.json({ ...common, id: '104', adset_id: '102', creative: { id: '103' }, effective_status: 'PENDING_REVIEW', issues_info: [] });
    if (u.pathname.endsWith('/104/insights')) { assert.deepEqual(JSON.parse(u.searchParams.get('time_range')!).until.length, 10); return Response.json({ data: rows }); }
    if (u.pathname.endsWith('/500')) return Response.json({ id: '500', status: { video_status: 'ready' }, length: 6, thumbnails: { data: [{ uri: 'https://example.com/real.jpg', width: 720, height: 1280, is_preferred: true }] } });
    throw new Error(`Unexpected request ${u.pathname}`);
  }) as typeof fetch;
  const attach = { expectedVersion: views.version, executionId: receipt.id, sourceCreativeId: creative.id };
  const beforeTask = await getPlatformAdTask('tenant', views.id), beforeReceipt = await store.getById('platform_ad_executions', receipt.id);
  await assert.rejects(attachExistingAdCreative('other-tenant', 'user', views.id, attach), /未找到/);
  await assert.rejects(attachExistingAdCreative('tenant', 'user', views.id, { ...attach, expectedVersion: 99 }), /当前版本/);
  await assert.rejects(getAdCreativeReport('other-tenant', receipt.id), /未找到/);
  await assert.rejects(getAdCreativePreview('other-tenant', creative.id), /未找到/);
  videoId = '501'; await assert.rejects(attachExistingAdCreative('tenant', 'user', views.id, attach), /不一致/); videoId = '500';
  accountId = '2'; await assert.rejects(attachExistingAdCreative('tenant', 'user', views.id, attach), /归属/); accountId = '1';
  status = 'ACTIVE'; await assert.rejects(attachExistingAdCreative('tenant', 'user', views.id, attach), /暂停/); status = 'PAUSED';
  const result = await attachExistingAdCreative('tenant', 'user', views.id, attach);
  assert.equal(result.reused, false);
  assert.equal((await attachExistingAdCreative('tenant', 'user', views.id, attach)).reused, true);
  assert.equal((await getPlatformAdCreative('tenant', result.creative.id))?.uploadReceipt?.mappingKind, 'post_execution');
  assert.deepEqual(await getPlatformAdTask('tenant', views.id), beforeTask, 'no plan mutation');
  assert.deepEqual(await store.getById('platform_ad_executions', receipt.id), beforeReceipt, 'no historical receipt mutation');
  const directory = await listAdCreativeLibrary('tenant', {});
  assert.equal(directory.items.find(i => i.execution?.id === receipt.id)?.mapping, 'verified_existing');
  assert.equal((await listAdCreativeLibrary('other-tenant', {})).items.length, 0);
  assert.ok(!JSON.stringify(directory).includes('secret-test-token'));
  assert.ok(!JSON.stringify(directory).includes('fileRef'));
  const empty = await getAdCreativeReport('tenant', receipt.id);
  assert.equal(empty.scope, 'ad'); assert.equal(empty.spend, null); assert.equal(empty.results, null); assert.equal(empty.effectiveStatus, 'PENDING_REVIEW');
  rows = [{ date_start: '2026-10-22', date_stop: '2026-10-22', spend: '12', impressions: '1000', clicks: '20', inline_link_clicks: '8', video_thruplay_watched_actions: [{ action_type: 'video_view', value: '6' }] }];
  clockOffset += 60_001;
  const positive = await getAdCreativeReport('tenant', receipt.id);
  assert.equal(positive.results, 6); assert.equal(positive.costPerResult, 2); assert.equal(positive.reportTimezone, 'Asia/Shanghai');
  rows = [{ ...rows[0], spend: '0', impressions: '0', clicks: '0', video_thruplay_watched_actions: [{ action_type: 'video_view', value: '0' }] }];
  clockOffset += 60_001;
  assert.equal((await getAdCreativeReport('tenant', receipt.id)).spend, 0, 'real zero differs from empty');
  assert.equal((await getAdCreativeReport('tenant', receipt.id)).costPerResult, null);
  assert.equal((await getAdCreativePreview('tenant', creative.id)).height, 1280);
  assert.ok(!requests.some(p => p.endsWith('/101/insights')), 'never attribute campaign totals to material');
  console.log('Creative library: tenant boundaries, immutable/idempotent post-execution mapping, ad-level empty/zero/positive metrics and real thumbnail readback passed (provider mocked, GET only).');
} finally { Date.now = originalNow; globalThis.fetch = originalFetch; fs.rmSync(temp, { recursive: true, force: true }); fs.rmSync(mediaDir, { recursive: true, force: true }); }

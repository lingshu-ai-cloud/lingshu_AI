import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'ad-oauth-'));
process.env.LOCAL_STORE_DIR = dir;
process.env.PB_URL = 'http://127.0.0.1:1';
process.env.NODE_ENV = 'test';
process.env.ENABLE_LOCAL_DEV_FALLBACK = 'true';
// Only this isolated fixture uses controlled provider transports and JSON leases.
process.env.TEST_ONLY_EXTERNAL_EFFECT_LEASE_FALLBACK = 'true';
process.env.DATA_BACKEND = 'pocketbase';
process.env.META_ADS_API_VERSION = 'v25.0';
process.env.META_ADS_APP_ID = '123';
process.env.META_ADS_LOGIN_MODE = 'classic';
process.env.META_ADS_APP_SECRET = 'private';
process.env.META_ADS_REDIRECT_URI = 'https://example.com/api/overseas/platform-ads/oauth/meta/callback';
const originalFetch = globalThis.fetch;
try {
  const { beginMetaOAuth, finishMetaOAuth, oauthAccounts, oauthPages, selectOAuthAccount, cancelMetaOAuth, metaOAuthReadiness } = await import('./oauth.js');
  const { store } = await import('../storage/index.js');
  const { readAuthorizationEdge } = await import('./metaAuthorization.js');
  const { MetaAdsAdapter } = await import('./metaAdapter.js');
  assert.equal(metaOAuthReadiness().configured, true);
  const first = await beginMetaOAuth('t1', 'u1');
  const url = new URL(first.url);
  assert.deepEqual(url.searchParams.get('scope')?.split(','), ['ads_read', 'ads_management', 'pages_show_list', 'pages_read_engagement', 'pages_manage_ads']);
  assert.ok(!first.url.includes('private'));
  await assert.rejects(oauthAccounts('t2', 'u1', first.sessionId), /无效/);
  let exchanges = 0;
  const effects: string[] = [];
  globalThis.fetch = (async (url: any, init: any) => {
    if (!String(url).startsWith('https://graph.facebook.com/')) return originalFetch(url, init);
    effects.push(`${init?.method || 'GET'} ${new URL(String(url)).pathname}`);
    if (String(url).includes('oauth/access_token')) { exchanges++; return Response.json({ access_token: 'top-secret' }); }
    const pathname = new URL(String(url)).pathname;
    if (pathname.endsWith('/me/accounts')) return Response.json({ data: [{ id: '10', name: 'Brand', tasks: ['ADVERTISE'], access_token: 'page-secret' }, { id: '20', name: 'Unrelated', tasks: ['ADVERTISE'] }, { id: '30', name: 'Read only', tasks: ['ANALYZE'] }] });
    if (pathname.endsWith('/promote_pages')) return Response.json({ data: [{ id: '10' }, { id: '30' }] });
    if (pathname.endsWith('/10')) return Response.json({ id: '10', access_token: 'page-secret' });
    if (pathname.endsWith('/act_1')) return Response.json({ id: 'act_1', account_id: '1', currency: 'USD', name: 'Account', account_status: 1, timezone_name: 'America/Los_Angeles' });
    const accountFields = new URL(String(url)).searchParams.get('fields')?.split(',') || [];
    for (const field of ['id', 'name', 'currency', 'account_status', 'timezone_name']) assert.ok(accountFields.includes(field));
    return Response.json({ data: [{ id: 'act_1', name: 'Account', currency: 'USD', account_status: 1, timezone_name: 'America/Los_Angeles' }] });
  }) as typeof fetch;
  const state = url.searchParams.get('state')!;
  await finishMetaOAuth(state, 'code');
  await assert.rejects(finishMetaOAuth(state, 'code'), /使用或过期/);
  assert.equal(exchanges, 1);
  const accounts = await oauthAccounts('t1', 'u1', first.sessionId);
  assert.equal(accounts.status, 'ready');
  assert.equal(accounts.accounts[0].id, 'act_1');
  assert.equal(accounts.accounts[0].accountStatus, 1);
  assert.equal(accounts.accounts[0].timezoneName, 'America/Los_Angeles');
  assert.ok(!JSON.stringify(accounts).includes('top-secret'));
  await assert.rejects(oauthPages('t2', 'u1', first.sessionId, 'act_1'), /无效/);
  await assert.rejects(oauthPages('t1', 'other-user', first.sessionId, 'act_1'), /无效/);
  await assert.rejects(oauthPages('t1', 'u1', first.sessionId, 'act_999'), /已授权/);
  assert.deepEqual(await oauthPages('t1', 'u1', first.sessionId, 'act_1'), [{ id: '10', name: 'Brand', tasks: ['ADVERTISE'] }]);
  await assert.rejects(selectOAuthAccount('t1', 'u1', first.sessionId, 'act_1', '20'), /范围/);
  await assert.rejects(selectOAuthAccount('t1', 'u1', first.sessionId, 'act_1', '30'), /范围/);
  assert.equal((await store.list('platform_ad_connections')).items.length, 0, 'reading/rejected choices never persist connections');
  const connection = await selectOAuthAccount('t1', 'u1', first.sessionId, 'act_1', '10');
  assert.equal(connection.defaultPage.id, '10');
  assert.equal((await selectOAuthAccount('t1', 'u1', first.sessionId, 'act_1', '10')).id, connection.id);
  assert.equal((await store.list('platform_ad_connections')).items.length, 1);
  assert.equal((await store.getById<any>('platform_ad_connections', connection.id))?.defaultPage.name, 'Brand');
  assert.ok(!JSON.stringify(connection).includes('top-secret') && !JSON.stringify(connection).includes('page-secret'));
  assert.ok(effects.every(e => e.startsWith('GET ') || e.endsWith('/oauth/access_token')), 'only token exchange is POST; no Meta asset writes');
  const cancelled = await beginMetaOAuth('t1', 'u1');
  await cancelMetaOAuth(new URL(cancelled.url).searchParams.get('state')!);
  assert.equal((await oauthAccounts('t1', 'u1', cancelled.sessionId)).status, 'cancelled');
  await assert.rejects(finishMetaOAuth(new URL(cancelled.url).searchParams.get('state')!, 'code'), /使用或过期/);
  const expired = await beginMetaOAuth('t1', 'u1');
  await store.update('platform_ad_oauth_states', expired.sessionId, { expiresAt: new Date(0).toISOString() });
  await assert.rejects(oauthAccounts('t1', 'u1', expired.sessionId), /过期/);
  const nativeFetch = globalThis.fetch;
  let reads = 0;
  globalThis.fetch = (async () => Response.json(++reads === 1 ? { data: [{ id: '1' }], paging: { next: 'https://evil.invalid/?access_token=secret', cursors: { after: 'second-page' } } } : { data: [{ id: '2' }] })) as typeof fetch;
  assert.equal((await readAuthorizationEdge(new MetaAdsAdapter('test'), 'me/adaccounts', 'id')).length, 2);
  globalThis.fetch = nativeFetch;
  // This is a URL contract, not a claim that the existing Meta app is configured.
  process.env.META_ADS_LOGIN_MODE = 'business';
  process.env.META_ADS_LOGIN_CONFIG_ID = '456';
  const business = await beginMetaOAuth('t1', 'u1');
  const businessUrl = new URL(business.url);
  assert.equal(businessUrl.searchParams.get('config_id'), '456');
  assert.equal(businessUrl.searchParams.has('scope'), false, 'business configuration must not be mixed with classic scope');
  const beforeContextChange = exchanges;
  process.env.META_ADS_OAUTH_ENVIRONMENT = 'other-environment';
  await assert.rejects(finishMetaOAuth(businessUrl.searchParams.get('state')!, 'code'), /无效/);
  assert.equal(exchanges, beforeContextChange, 'a foreign environment cannot even exchange the authorization code');
  delete process.env.META_ADS_OAUTH_ENVIRONMENT;
  await finishMetaOAuth(businessUrl.searchParams.get('state')!, 'code');
  assert.equal((await oauthAccounts('t1', 'u1', business.sessionId)).status, 'ready');
  process.env.META_ADS_LOGIN_MODE = 'classic';
  delete process.env.META_ADS_APP_SECRET;
  assert.equal(metaOAuthReadiness().configured, false);
  assert.deepEqual(metaOAuthReadiness().missing, ['META_ADS_APP_SECRET']);
  await assert.rejects(beginMetaOAuth('t1', 'u1'), /尚未配置/);
  console.log('ad OAuth tests passed');
} finally { globalThis.fetch = originalFetch; fs.rmSync(dir, { recursive: true, force: true }); }

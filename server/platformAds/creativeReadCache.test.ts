import assert from 'node:assert/strict';
import { creativeReadCache } from './creativeReadCache.js';
const cache = creativeReadCache<{ n: number }>(1000, 2);
let count = 0;
const read = async () => ({ n: ++count });
const [a, b] = await Promise.all([cache('tenant-a', 'ad', read), cache('tenant-a', 'ad', read)]);
assert.equal(count, 1); assert.deepEqual(a, b);
a.n = 99;
assert.equal((await cache('tenant-a', 'ad', read)).n, 1, 'callers cannot mutate cached evidence');
assert.equal((await cache('tenant-b', 'ad', read)).n, 2, 'no cross-tenant cache reuse');
await cache('tenant-c', 'ad', read);
assert.equal((await cache('tenant-a', 'ad', read)).n, 4, 'bounded eviction');
const failed = creativeReadCache<number>(1000);
await assert.rejects(failed('tenant', 'failed', async () => { throw Error('limited'); }), /limited/);
assert.equal(await failed('tenant', 'failed', async () => 1), 1, 'errors are not cached as successful data');
const expired = creativeReadCache<number>(-1);
assert.equal(await expired('tenant', 'ad', async () => 1), 1);
assert.equal(await expired('tenant', 'ad', async () => 2), 2);
console.log('Creative read cache: concurrent de-duplication, tenant isolation, immutable copies, bounded eviction, expiry and error recovery passed.');

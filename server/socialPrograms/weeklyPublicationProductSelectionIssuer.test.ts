import test from 'node:test';
import assert from 'node:assert/strict';
import {prepareWeeklyEnterpriseFactFixture,reopenWeeklyEnterpriseFactFixtureStore} from '../runtime/weeklyEnterpriseFactSupplement.fixture.js';
import {readWeeklyPublicationProductSelectionChoices,readWeeklyPublicationProductSelection,issueWeeklyPublicationProductSelections,WEEKLY_PUBLICATION_PRODUCT_SELECTIONS,WEEKLY_PUBLICATION_PRODUCT_SELECTION_ISSUANCES} from './weeklyPublicationProductSelection.js';
import {createSocialOperatingRepository} from '../socialOperating/repository.js';
import {mkdtempSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';

test('authenticated batch signs every publication, preserves mother group, and survives datastore restart',async t=>{
 const directory=mkdtempSync(join(tmpdir(),'weekly-selection-')),file=join(directory,'store.json');
 const f=await prepareWeeklyEnterpriseFactFixture(t,{persistentFile:file});
 const scope={tenantId:f.task.tenantId,programId:f.task.programId,packageId:f.task.packageId,packageVersion:1};
 const pkgRow=(await f.store.list<any>('social_weekly_operating_packages')).items[0]!;
 const base={...pkgRow.payload.socialContentPackage.publicationTasks[0],motherContentId:'mother-a',status:'planned'};
 const publications=[{...base,publicationTaskId:'pub-1'},{...base,publicationTaskId:'pub-2'}];
 await f.store.update('social_weekly_operating_packages',pkgRow.id,{payload:{...pkgRow.payload,socialContentPackage:{...pkgRow.payload.socialContentPackage,publicationTasks:publications}}});
 const goalRef=pkgRow.payload.businessContentGoalRef;
 const goal=await createSocialOperatingRepository(f.store).getGoal(scope.tenantId,scope.programId,goalRef.id,goalRef.version);
 assert(goal);
 const profileRow=(await f.store.list<any>('tenant_profiles')).items[0]!;
 const product=profileRow.profile.products.items[0];
 assert(product.id&&goal.products.includes(product.name));
 const before=await readWeeklyPublicationProductSelectionChoices(f.store,scope);
 assert.deepEqual(before.publications.map(p=>p.selectedProductId),[null,null]);
 await assert.rejects(issueWeeklyPublicationProductSelections(f.store,scope,'owner',{expectedContextHash:before.contextHash,productId:product.id,publicationTaskIds:['pub-1']}),/weekly_product_selection_mother_group_incomplete/);
 const input={expectedContextHash:before.contextHash,productId:product.id,publicationTaskIds:['pub-1','pub-2']};
 const create=f.store.create.bind(f.store);
 f.store.create=async <T>(collection:string,data:Record<string,unknown>)=>collection===WEEKLY_PUBLICATION_PRODUCT_SELECTIONS?null:create<T>(collection,data);
 await assert.rejects(issueWeeklyPublicationProductSelections(f.store,scope,'owner',input),/weekly_product_selection_receipt_conflict/);
 assert.equal((await f.store.list(WEEKLY_PUBLICATION_PRODUCT_SELECTIONS)).totalItems,0);
 const pending=await readWeeklyPublicationProductSelectionChoices(f.store,scope);
 assert.equal(pending.selectionState,'pending_operation');
 assert.deepEqual(pending.publications.map(p=>p.pendingOperation),[true,false]);
 assert.deepEqual(pending.publications.map(p=>p.pendingProductId),[product.id,null]);
 const operation=(await f.store.list<any>(WEEKLY_PUBLICATION_PRODUCT_SELECTION_ISSUANCES)).items[0]!;
 await f.store.update(WEEKLY_PUBLICATION_PRODUCT_SELECTION_ISSUANCES,operation.id,{content_hash:'0'.repeat(64)});
 await assert.rejects(readWeeklyPublicationProductSelectionChoices(f.store,scope),/weekly_product_selection_issuance_invalid/);
 await f.store.update(WEEKLY_PUBLICATION_PRODUCT_SELECTION_ISSUANCES,operation.id,{content_hash:operation.content_hash});
 await assert.rejects(readWeeklyPublicationProductSelection({...scope,store:f.store,publication:publications[0],goal}),/weekly_product_selection_issuance_pending/);
 f.store.create=create;
 let interrupted=false;
 f.store.create=async <T>(collection:string,data:Record<string,unknown>)=>{if(!interrupted&&collection===WEEKLY_PUBLICATION_PRODUCT_SELECTIONS&&data.publication_task_id==='pub-2'){interrupted=true;return null;}return create<T>(collection,data);};
 await assert.rejects(issueWeeklyPublicationProductSelections(f.store,scope,'owner',input),/weekly_product_selection_receipt_conflict/);
 assert.equal((await f.store.list(WEEKLY_PUBLICATION_PRODUCT_SELECTIONS)).totalItems,1);
 assert.equal((await readWeeklyPublicationProductSelectionChoices(f.store,scope)).selectionState,'pending_operation');
 await assert.rejects(readWeeklyPublicationProductSelection({...scope,store:f.store,publication:publications[0],goal}),/weekly_product_selection_issuance_pending/);
 f.store.create=create;
 const after=await issueWeeklyPublicationProductSelections(f.store,scope,'owner',input);
 assert.equal(after.selectionState,'consistent');
 assert.deepEqual(after.publications.map(p=>p.selectedProductId),[product.id,product.id]);
 assert.equal((await f.store.list(WEEKLY_PUBLICATION_PRODUCT_SELECTIONS)).totalItems,2);
 assert.equal((await f.store.list(WEEKLY_PUBLICATION_PRODUCT_SELECTION_ISSUANCES)).totalItems,2);
 const reopened=reopenWeeklyEnterpriseFactFixtureStore(file);
 assert.deepEqual((await readWeeklyPublicationProductSelectionChoices(reopened,scope)).publications,after.publications);
 await issueWeeklyPublicationProductSelections(reopened,scope,'owner',input);
 assert.equal((await reopened.list(WEEKLY_PUBLICATION_PRODUCT_SELECTIONS)).totalItems,2);
 await assert.rejects(issueWeeklyPublicationProductSelections(reopened,scope,'outsider',input),/weekly_product_selection_actor_forbidden/);
 const actor=await reopened.getById<any>('users','owner');
 assert(actor);
 await reopened.update('users','owner',{role:'customer_service'});
 await assert.rejects(readWeeklyPublicationProductSelection({...scope,store:reopened,publication:publications[0],goal}),/weekly_product_selection_actor_revoked/);
 await assert.rejects(readWeeklyPublicationProductSelectionChoices(reopened,scope),/weekly_product_selection_actor_revoked/);
 await assert.rejects(issueWeeklyPublicationProductSelections(reopened,scope,'owner',input),/weekly_product_selection_actor_forbidden/);
 assert.equal((await reopened.list(WEEKLY_PUBLICATION_PRODUCT_SELECTIONS)).totalItems,2,'demotion must not delete immutable audit receipts');
 await reopened.update('users','owner',{role:actor.role});
 assert.equal((await readWeeklyPublicationProductSelectionChoices(reopened,scope)).selectionState,'consistent');
});

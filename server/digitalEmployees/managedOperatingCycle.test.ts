import assert from 'node:assert/strict';
import { nextManagedCycleWindow, prepareManagedCyclePackage } from './managedOperatingCycle.js';
import { normalizeDigitalEmployeeConfig, normalizeWeeklyGoal } from './domain.js';
import { recommendPackage } from './weeklyPackage.js';
const now = new Date('2099-01-05T01:00:00Z');
const source = { starts_at: '2098-12-29', ends_at: '2099-01-04' };
assert.equal(nextManagedCycleWindow(source, new Date('2099-01-04T12:00:00Z')), null);
assert.deepEqual(nextManagedCycleWindow(source, now), { startsAt: '2099-01-05', endsAt: '2099-01-11' });
assert.deepEqual(nextManagedCycleWindow(source, new Date('2099-01-20T01:00:00Z')), { startsAt: '2099-01-19', endsAt: '2099-01-25' });
const config = normalizeDigitalEmployeeConfig({ companyName: 'Test', focusProducts: 'A', autonomyMode: 'automatic', allowRealPublishing: true, publishingTargets: [{ accountId: 'a', platform: 'youtube', accountLabel: 'A' }], managedPublishingGrant: { enabled: true, grantId: 'g', authorizedBy: 'user', accountIds: ['a'], maxPublishItems: 3, validUntil: '2099-01-31' } });
const pack = recommendPackage(normalizeWeeklyGoal({ startsAt: source.starts_at, endsAt: source.ends_at, contentPlatforms: ['youtube'] }, config), config);
pack.directorPlan!.productionBudget = 80;
pack.directorPlan!.productionSpent = 20;
const next = prepareManagedCyclePackage(pack, config, '2099-01-11', ['保留真实产品证据'], now)!;
assert.ok(next);
assert.equal(prepareManagedCyclePackage(pack, { ...config, managedPublishingGrant: { ...config.managedPublishingGrant!, maxPublishItems: 2 } }, '2099-01-11', [], now), null, 'a three-item weekly plan must not exceed a two-item grant');
assert.equal(next.pack.directorPlan!.productionBudget, 80);
assert.equal(next.pack.directorPlan!.productionSpent, 0);
assert.equal(pack.directorPlan!.productionSpent, 20);
assert.equal(next.pack.tasks.some(task => task.templateId === 'followup' || task.templateId === 'customers'), false);
assert.match(next.pack.tasks.find(task => task.templateId === 'director')!.notes, /保留真实产品证据/);
assert.equal(prepareManagedCyclePackage(pack, { ...config, managedPublishingGrant: undefined }, '2099-01-11', [], now), null);
assert.equal(prepareManagedCyclePackage(pack, config, '2099-02-01', [], now), null);
assert.equal(prepareManagedCyclePackage({ ...pack, participation: 'team' }, config, '2099-01-11', [], now), null);
assert.equal(prepareManagedCyclePackage({ ...pack, directorPlan: undefined }, config, '2099-01-11', [], now), null, 'unbounded legacy budgets cannot silently recur');
console.log('Managed operating cycle windows, per-cycle budgets, and consent boundaries passed');

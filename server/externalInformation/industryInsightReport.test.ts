import assert from 'node:assert/strict';
import test from 'node:test';
import { industrySourceType, deduplicateIndustrySignals, industryInsightBlock, industryInsightScope, industryInsightSummary, type IndustrySignal } from './industryInsightReport.js';
const signal: IndustrySignal = { title: 'Research update', category: '产品与技术', publishedAt: '2026-10-20', fact: '企业发布新型配方研究结果，实际适配仍需验证。', implication: '可能帮助商户选择后续配方研究方向。', action: '建议先核对技术资料与适用条件。', sourceTitle: 'Original research update', sourceUrl: 'https://publisher.com/news/article', quote: 'The company announced new formulation research.' };

test('scope labels survive repeated scene prefixes and use bounded enterprise scope only as fallback', () => {
 assert.deepEqual(industryInsightScope('行业资讯。行业资讯：行业：美妆原料，目标市场：欧洲。'), { industry: '美妆原料', market: '欧洲' });
 assert.deepEqual(industryInsightScope('行业资讯。已明确的查询范围：{"industry":"美妆原料","market":"欧洲"}。'), { industry: '美妆原料', market: '欧洲' });
 assert.deepEqual(industryInsightScope('行业资讯。行业：机械，市场：美国。已明确的查询范围：{"industry":"纺织","market":"欧洲"}。'), { industry: '机械', market: '美国' });
 assert.deepEqual(industryInsightScope('行业资讯。已明确的查询范围：{"industry":"以用户本轮指定为准","market":"以用户本轮指定为准"}。'), { industry: '', market: '' });
 assert.deepEqual(industryInsightScope('行业资讯。已明确的查询范围：{broken}。'), { industry: '', market: '' });
});

test('identical events or tracking aliases cannot inflate report sample counts', () => {
 const duplicateFact = { ...signal, sourceUrl: 'https://otherpublisher.com/reprint' };
 const tracked = { ...signal, fact: '另一条介绍。', quote: 'A separate excerpt.', sourceUrl: signal.sourceUrl + '?utm_source=feed#top' };
 const duplicateQuote = { ...signal, fact: '不同标题与转述，但相同原文。', sourceUrl: 'https://anotherpublisher.com/reprint' };
 assert.deepEqual(deduplicateIndustrySignals([signal, duplicateFact, tracked, duplicateQuote]), [signal]);
});

test('version one remains compatible with uniform topic title, source attribution and concise AI footer', () => {
 const block = industryInsightBlock('行业资讯：行业：美妆原料，目标市场：欧洲。', [signal], industryInsightSummary([signal]), 0, 30);
 const report = JSON.parse(block.split('\n')[1]);
 assert.equal(report.version, 1); assert.equal(report.signals.length, 1);
 assert.equal(report.industry, '美妆原料'); assert.equal(report.market, '欧洲');
 assert.equal(report.title, '专题观察'); assert.match(report.summary, /专题观察重点/);
 assert.deepEqual(report.limitations, ['AI结论仅供参考']); assert.equal(report.signals[0].sourceType, '公开资料');
 assert.doesNotMatch(report.summary, /不能|不足|不代表/);
 assert.ok(!report.summary.includes('Research update'));
});


test('AI-generated article disclosure is retained as source attribution rather than exclusion', () => {
 for (const text of [
  '文章由AI基于公开信息生成，仅供参考。',
  '本文使用人工智能技术撰写，信息可能存在错误。',
  '本内容由人工智能自动生成，不代表平台立场。',
  'This article was generated by AI based on public information.',
 ]) assert.equal(industrySourceType(text), 'AI整理内容', text);
 assert.notEqual(industrySourceType('企业发布AI生成工具，研究人员介绍其检测方法与实际试验结果。'), 'AI整理内容');
 assert.notEqual(industrySourceType('本文由编辑团队撰写，介绍人工智能辅助分析的研究方法。'), 'AI整理内容');
 assert.notEqual(industrySourceType('本文由编辑团队撰写，介绍人工智能生成工具的试验结果。'), 'AI整理内容');
});

test('commercial research is retained with attribution and no publisher blacklist', () => {
 assert.equal(industrySourceType('报告内容摘要：预计市场将快速增长。报告目录：第一章市场预测，第二章产品分析。详细信息以最终报告为准，欢迎订购报告。'), '商业研究报告');
 assert.equal(industrySourceType('Report summary: a market forecast. Table of contents: market overview. Purchase the report for complete details.'), '商业研究报告');
 for (const text of [
  '行业媒体采访企业并核对公开披露，正文列出实际合作进展及产品测试条件。',
  '研究摘要：方法采用公开样本和对照试验，结果报告观察到的变化并说明局限。',
  '企业官网公布研发与合作情况，相关预测存在不确定性，执行情况见正式公告。',
  '报告摘要和报告目录公开提供，完整研究同时展示方法、样本范围与原始结果。',
 ]) assert.ok(industrySourceType(text), text);
});


test('topic observations retain commercial and AI-attributed signals without repeating protective body messages', () => {
 const values = [
  { ...signal, fact: '研究机构预计该市场规模将增长，具体期间沿用来源。', quote: 'Report summary with forecast.', sourceUrl: 'https://researchpublisher.com/report', sourceType: '商业研究报告' },
  { ...signal, fact: '公开评论整理了品牌竞争与渠道变化。', quote: 'Public commentary on brand competition.', sourceUrl: 'https://mediapublisher.com/commentary', sourceType: 'AI整理内容' },
 ];
 const report = JSON.parse(industryInsightBlock('行业资讯：行业：美妆原料，目标市场：欧洲。', values, industryInsightSummary(values), 12, 30).split('\n')[1]);
 assert.equal(report.signals.length, 2);
 assert.deepEqual(report.signals.map((value: { sourceType: string }) => value.sourceType), ['商业研究报告', 'AI整理内容']);
 assert.equal(report.title, '专题观察');assert.deepEqual(report.limitations, ['AI结论仅供参考']);
});

test('source-attributed public market metrics remain available for topic visualizations', () => {
 const metrics = [{ label: '市场规模', period: '2030年', value: 120, unit: '亿美元', kind: 'forecast' as const,
  sourceUrl: signal.sourceUrl, sourceTitle: signal.sourceTitle, quote: 'Research estimates market size at USD 12 billion by 2030.' }];
 const report = JSON.parse(industryInsightBlock('行业资讯：行业：美妆原料，目标市场：欧洲。', [signal], '专题观察结论。', 0, 30, metrics).split('\n')[1]);
 assert.deepEqual(report.metrics, metrics);
 assert.equal(report.metrics[0].kind, 'forecast');
 assert.deepEqual(report.limitations, ['AI结论仅供参考']);
});

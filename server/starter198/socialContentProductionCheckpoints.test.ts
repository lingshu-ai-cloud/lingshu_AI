test('material analysis, storyboard and shot-material mapping resume across a fresh worker context', async () => {
  const store = new MemoryStore();
  const job = await admitContentExecutionJob({
    dataStore: store, tenantId: 'tenant-checkpoint', userId: 'user-a', taskId: 'task-a',
    runId: 'run-a', taskType: 'social_content_weekly',
  });
  let analysisCalls = 0;
  const firstRaw = rawAsset('/tmp/worker-a/source.mp4');
  await runWithContentExecutionContext({ dataStore: store, jobId: job.id, action: async () => {
    const analyzed = await analyzeSocialProductionAssetsWithCheckpoint({
      tenantId: 'tenant-checkpoint', assets: [firstRaw],
      analyze: async ({ assets }) => {
        analysisCalls += 1;
        return {
          assets: assets.map(asset => ({
            ...asset,
            visualObservations: ['产品瓶身与标签可见'],
            segments: [{ start: 0, end: 4, description: '产品近景' }],
          })),
          failures: [],
        };
      },
    });
    assert.equal(analyzed.checkpointReused, false);
    await recordCurrentContentExecutionCheckpoint({
      stage: 'social.asset_supply', version: '1', inputHash: 'supply-v1',
      payload: { shots: [{ sceneId: 'scene-1', assetId: 'asset-1', start: 0, end: 4 }] },
    });
    await recordCurrentContentExecutionCheckpoint({
      stage: 'social.director_storyboard', version: '1', inputHash: 'director-v1',
      payload: { scenes: [{ sceneId: 'scene-1', voiceover: '看真实产品细节。', assetId: 'asset-1' }] },
    });
  } });

  const persisted = await readContentExecutionJob(store, 'tenant-checkpoint', 'task-a', 'run-a');
  await runWithContentExecutionContext({
    dataStore: store, jobId: job.id, checkpoints: persisted?.checkpoints,
    action: async () => {
      const analyzed = await analyzeSocialProductionAssetsWithCheckpoint({
        tenantId: 'tenant-checkpoint',
        // Local materialization and signed URL may change after a restart; the
        // stable content identity must still reuse the analysis.
        assets: [{ ...rawAsset('/tmp/worker-b/source.mp4'), url: 'https://signed.example/refreshed' }],
        analyze: async () => { throw new Error('analysis_must_not_repeat'); },
      });
      assert.equal(analyzed.checkpointReused, true);
      assert.deepEqual(analyzed.assets[0]?.visualObservations, ['产品瓶身与标签可见']);
      assert.deepEqual(readCurrentContentExecutionCheckpoint({
        stage: 'social.asset_supply', version: '1', inputHash: 'supply-v1',
      }), { shots: [{ sceneId: 'scene-1', assetId: 'asset-1', start: 0, end: 4 }] });
      assert.deepEqual(readCurrentContentExecutionCheckpoint({
        stage: 'social.director_storyboard', version: '1', inputHash: 'director-v1',
      }), { scenes: [{ sceneId: 'scene-1', voiceover: '看真实产品细节。', assetId: 'asset-1' }] });
    },
  });
  assert.equal(analysisCalls, 1);
});

test('narration audio, alignment cues and render timing survive worker restart without a second TTS call', async () => {
  const store = new MemoryStore();
  const job = await admitContentExecutionJob({
    dataStore: store, tenantId: 'tenant-voice', userId: 'user-a', taskId: 'task-voice',
    runId: 'run-voice', taskType: 'social_content_weekly',
  });
  const narration = '看真实产品细节。';
  const inputHash = 'voice-input-v1';
  const audioPath = path.resolve(process.cwd(), 'data', 'tts', `checkpoint-test-${process.pid}.wav`);
  await fsp.mkdir(path.dirname(audioPath), { recursive: true });
  await fsp.writeFile(audioPath, Buffer.from('durable-test-audio'));
  try {
    await runWithContentExecutionContext({ dataStore: store, jobId: job.id, action: async () => {
      assert.equal(await recordNarrationAudioCheckpoint({
        inputHash,
        narration,
        voice: {
          ok: true, source: 'test-tts', localPath: audioPath, duration: 2.4, text: narration,
          alignmentSource: 'provider_words',
          cues: [{ text: narration, start: 0, end: 2.4, words: [{ text: '产品', start: 0.4, end: 0.9 }] }],
        },
        captionCues: [{ text: narration, start: 0, end: 2.4 }],
        renderTimeline: [{ sceneId: 'scene-1', start: 0, end: 2.4 }],
      }), true);
    } });
    const persisted = await readContentExecutionJob(store, 'tenant-voice', 'task-voice', 'run-voice');
    let ttsCalls = 0;
    await runWithContentExecutionContext({
      dataStore: store, jobId: job.id, checkpoints: persisted?.checkpoints,
      action: async () => {
        const recovered = await readNarrationAudioCheckpoint({ inputHash, narration });
        if (!recovered) ttsCalls += 1;
        assert.equal(recovered?.localPath, audioPath);
        assert.equal(recovered?.duration, 2.4);
        assert.equal(recovered?.cues[0]?.words?.[0]?.text, '产品');
        const persistedTiming = readCurrentContentExecutionCheckpoint<{
          captionCues: unknown[];
          renderTimeline: unknown[];
        }>({ stage: 'social.narration_audio', version: '1', inputHash });
        assert.equal(persistedTiming?.captionCues.length, 1);
        assert.equal(persistedTiming?.renderTimeline.length, 1);
      },
    });
    assert.equal(ttsCalls, 0);
  } finally {
    await fsp.rm(audioPath, { force: true });
  }
});

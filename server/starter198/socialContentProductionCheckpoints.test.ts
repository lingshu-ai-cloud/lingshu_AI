test('generated asset checkpoint restores verified bytes and otherwise requires provider reconciliation', async () => {
  const localPath = path.resolve(process.cwd(), 'data', `generated-checkpoint-${process.pid}.mp4`);
  await fsp.mkdir(path.dirname(localPath), { recursive: true });
  await fsp.writeFile(localPath, Buffer.from('generated-video'));
  const generated: SocialProductionAsset = {
    id: 'generated-asset', sourceId: 'seedance-source', name: 'generated.mp4', type: 'video',
    url: 'https://provider.example/output.mp4', localPath, contentHash: 'generated-sha',
    providerId: 'seedance', providerTaskId: 'provider-task-1', idempotencyKey: 'stable-key-1',
    duration: 5, visualObservations: ['generated product scene'], segments: [],
  };
  const selectedAssets = [{
    assetId: generated.id, sourceId: generated.sourceId, contentHash: generated.contentHash ?? null,
    asset: generated,
  }];
  try {
    assert.equal(restoreSocialAssetSupplyCheckpointAssets({
      availableAssets: [], selectedAssets,
    })?.[0]?.providerTaskId, 'provider-task-1');
  } finally {
    await fsp.rm(localPath, { force: true });
  }
  assert.equal(restoreSocialAssetSupplyCheckpointAssets({
    availableAssets: [], selectedAssets,
  }), null, 'missing generated bytes must fall back to receipt reconciliation, not a new submission');
});

class MemoryStore implements DataStore {
  private rows = new Map<string, Map<string, Record<string, unknown> & { id: string }>>();
  private sequence = 0;
  private collection(name: string) {
    let value = this.rows.get(name);
    if (!value) { value = new Map(); this.rows.set(name, value); }
    return value;
  }
  async getById<T>(collection: string, id: string): Promise<T | null> {
    return (this.collection(collection).get(id) as T | undefined) ?? null;
  }
  async create<T>(collection: string, data: Record<string, unknown>): Promise<T | null> {
    const target = this.collection(collection);
    const id = String(data.id || `row${++this.sequence}`);
    if (target.has(id)) return null;
    const row = { ...data, id } as Record<string, unknown> & { id: string };
    target.set(id, row);
    return row as T;
  }
  async update(collection: string, id: string, data: Record<string, unknown>): Promise<boolean> {
    const prior = this.collection(collection).get(id);
    if (!prior) return false;
    this.collection(collection).set(id, { ...prior, ...structuredClone(data), id });
    return true;
  }
  async delete(collection: string, id: string): Promise<boolean> {
    return this.collection(collection).delete(id);
  }
  async list<T>(collection: string, query: ListQuery = {}): Promise<ListResult<T>> {
    const items = [...this.collection(collection).values()].filter(row => Object.entries(query.where || {})
      .every(([key, value]) => row[key] === value));
    return { items: items as T[], totalItems: items.length, totalPages: items.length ? 1 : 0, page: 1, perPage: query.perPage || 20 };
  }
}


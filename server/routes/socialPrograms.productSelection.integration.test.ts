import test from 'node:test';
import assert from 'node:assert/strict';
import type {AddressInfo} from 'node:net';
import express from 'express';
import {auth} from '../storage/index.js';
import {prepareWeeklyEnterpriseFactFixture} from '../runtime/weeklyEnterpriseFactSupplement.fixture.js';
import {createSocialProgramsRouter} from './socialPrograms.js';
import {WEEKLY_PUBLICATION_PRODUCT_SELECTIONS} from '../socialPrograms/weeklyPublicationProductSelection.js';
import {adoptWeeklyAutomationTemplate} from '../socialPrograms/weeklyAutomationTemplate.js';
import {readWeeklyCtaContactCard,saveWeeklyCtaContact} from '../socialPrograms/weeklyCtaContact.js';

test('product-selection HTTP requires real scoped identity, exact context and full mother group',async t=>{
 const f=await prepareWeeklyEnterpriseFactFixture(t),row=(await f.store.list<any>('social_weekly_operating_packages')).items[0]!;
 const base={...row.payload.socialContentPackage.publicationTasks[0],motherContentId:'mother-a',status:'planned'};
 await f.store.update('social_weekly_operating_packages',row.id,{payload:{...row.payload,socialContentPackage:{...row.payload.socialContentPackage,publicationTasks:[{...base,publicationTaskId:'pub-1'},{...base,publicationTaskId:'pub-2'}]}}});
 const scope={tenantId:'tenant-a',programId:'program-a',packageId:'package-a',packageVersion:1};
 await adoptWeeklyAutomationTemplate(f.store,scope,'owner');
 const contactBefore=await readWeeklyCtaContactCard(f.store,scope);
 assert.equal(contactBefore.selectedProduct,null);
 const savedContact=await saveWeeklyCtaContact(f.store,scope,'owner',{contactChannel:'whatsapp',contactValue:'+8619653282176',expectedContextHash:contactBefore.contextHash,expectedReceiptId:null});
 assert.equal(savedContact.status,'recorded');
 await f.store.create('users',{id:'viewer',tenantId:'tenant-a',role:'viewer',active:true});
 await f.store.create('users',{id:'foreign',tenantId:'tenant-b',role:'admin',active:true});
 t.mock.method(auth,'verifyToken',async(header?:string)=>{const found=/^Bearer (owner|viewer|foreign)$/.exec(header??'');return found?{userId:found[1]!,tenantId:found[1]==='foreign'?'tenant-b':'tenant-a'}:null;});
 const app=express();app.use(express.json());app.use('/api/overseas/social-programs',createSocialProgramsRouter(f.store));app.use((error:any,_req:express.Request,res:express.Response,_next:express.NextFunction)=>res.status(error.status??500).json({error:error.code??'internal_error'}));
 const server=app.listen(0,'127.0.0.1');await new Promise<void>(resolve=>server.once('listening',resolve));t.after(()=>{server.closeAllConnections();return new Promise<void>(resolve=>server.close(()=>resolve()));});
 const root=`http://127.0.0.1:${(server.address() as AddressInfo).port}/api/overseas/social-programs/program-a/operating-packages/package-a/product-selection`;
 const request=(method:string,actor:string,body?:unknown)=>fetch(`${root}${method==='GET'?'?version=1':''}`,{method,headers:{authorization:`Bearer ${actor}`,'content-type':'application/json'},...(body?{body:JSON.stringify(body)}:{})});
 assert.equal((await fetch(`${root}?version=1`)).status,401);
 assert.equal((await request('GET','foreign')).status,404);
 const get=await request('GET','owner');assert.equal(get.status,200,await get.clone().text());const choices=(await get.json()).item;
 assert.deepEqual(choices.publications.map((p:any)=>p.selectedProductId),[null,null]);
 const product=choices.products[0];assert(product.id);
 const body={expectedPackageVersion:1,expectedContextHash:choices.contextHash,productId:product.id,publicationTaskIds:['pub-1','pub-2']};
 assert.equal((await request('POST','viewer',body)).status,403);
 assert.equal((await request('POST','foreign',body)).status,404);
 assert.equal((await request('POST','owner',{...body,authorizesPublishing:true})).status,400);
 assert.equal((await request('POST','owner',{...body,expectedContextHash:'0'.repeat(64)})).status,409);
 assert.equal((await request('POST','owner',{...body,publicationTaskIds:['pub-1']})).status,409);
 assert.equal((await f.store.list(WEEKLY_PUBLICATION_PRODUCT_SELECTIONS)).totalItems,0);
 const selected=await request('POST','owner',body);assert.equal(selected.status,200,await selected.clone().text());
 assert.deepEqual((await selected.json()).item.publications.map((p:any)=>p.selectedProductId),[product.id,product.id]);
 const contactAfter=await readWeeklyCtaContactCard(f.store,scope);
 assert.equal(contactAfter.status,'recorded','publication selection must not invalidate the independent contact receipt');
 assert.deepEqual(contactAfter.selectedProduct,{productId:product.id,name:product.name});
 assert.equal(contactAfter.productSelectionStatus,'selected');
 assert.equal(contactAfter.contextHash,contactBefore.contextHash);
 assert.equal(contactAfter.samplePromiseConfirmed,false);
 const refreshed=await fetch(`${root.replace('/product-selection','')}/cta-contact?version=1`,{headers:{authorization:'Bearer owner'}});
 assert.equal(refreshed.status,200);
 const refreshedItem=(await refreshed.json()).item;
 assert.deepEqual(refreshedItem.selectedProduct,contactAfter.selectedProduct);
 assert.equal(refreshedItem.samplePromiseConfirmed,false);
 const selectionRows=await f.store.list<any>(WEEKLY_PUBLICATION_PRODUCT_SELECTIONS);
 await f.store.update(WEEKLY_PUBLICATION_PRODUCT_SELECTIONS,selectionRows.items[0]!.id,{content_hash:'tampered'});
 const damaged=await readWeeklyCtaContactCard(f.store,scope);
 assert.equal(damaged.status,'recorded','display failure must not erase the contact receipt');
 assert.equal(damaged.selectedProduct,null,'a damaged product receipt must not be displayed as verified');
 assert.equal(damaged.productSelectionStatus,'unavailable');
 assert.equal(damaged.samplePromiseConfirmed,false);
});

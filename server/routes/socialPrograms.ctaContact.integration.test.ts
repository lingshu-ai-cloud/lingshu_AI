import test from 'node:test';
import assert from 'node:assert/strict';
import type { AddressInfo } from 'node:net';
import express from 'express';
import { auth } from '../storage/index.js';
import { prepareWeeklyEnterpriseFactFixture } from '../runtime/weeklyEnterpriseFactSupplement.fixture.js';
import { adoptWeeklyAutomationTemplate } from '../socialPrograms/weeklyAutomationTemplate.js';
import { WEEKLY_CTA_CONTACTS } from '../socialPrograms/weeklyCtaContact.js';
import { createSocialProgramsRouter } from './socialPrograms.js';

test('authenticated CTA HTTP card preserves scope, CAS revisions and sample-policy blocker', async t => {
  const f = await prepareWeeklyEnterpriseFactFixture(t);
  const scope = { tenantId: f.task.tenantId, programId: f.task.programId, packageId: f.task.packageId, packageVersion: 1 };
  await adoptWeeklyAutomationTemplate(f.store, scope, 'owner');
  const goal = (await f.store.list<any>('social_business_content_goals')).items[0]!;
  await f.store.update('social_business_content_goals', goal.id, { payload: { ...goal.payload, products: Array.from({ length: 21 }, (_, i) => `product-${i}`) } });
  const packageRow = (await f.store.list<any>('social_weekly_operating_packages')).items[0]!;
  await f.store.update('social_weekly_operating_packages', packageRow.id, { payload: { ...packageRow.payload, appliedWorkflowEvents: [], workflows: [] } });
  await f.store.create('users', { id: 'outsider', tenantId: 'other-tenant', role: 'social_operator', active: true });
  await f.store.create('users', { id: 'viewer', tenantId: scope.tenantId, role: 'viewer', active: true });
  await f.store.create('social_weekly_execution_tasks', { id: f.task.taskId, tenant_id: scope.tenantId, program_id: scope.programId, package_id: scope.packageId, package_version: 1, task_id: f.task.taskId, payload: { ...f.task, status: 'blocked', ownBlockingReasons: ['cta_required', 'business_proposition_required'] } });
  t.mock.method(auth, 'verifyToken', async (header?: string) => {
    const parts = /^Bearer (owner|outsider|viewer)@(tenant-a|other-tenant)$/.exec(header ?? '');
    return parts ? { userId: parts[1]!, tenantId: parts[2]! } : null;
  });
  const app = express();
  app.use(express.json());
  app.use('/api/overseas/social-programs', createSocialProgramsRouter(f.store));
  app.use((error: any, _req: express.Request, res: express.Response, _next: express.NextFunction) => res.status(error.status ?? 500).json({ error: error.code ?? 'internal_error' }));
  const server = app.listen(0, '127.0.0.1');
  await new Promise<void>(resolve => server.once('listening', resolve));
  t.after(() => { server.closeAllConnections(); return new Promise<void>(resolve => server.close(() => resolve())); });
  const root = `http://127.0.0.1:${(server.address() as AddressInfo).port}/api/overseas/social-programs/${scope.programId}/operating-packages/${scope.packageId}`;
  const headers = (who = 'owner', tenant = 'tenant-a') => ({ authorization: `Bearer ${who}@${tenant}`, 'content-type': 'application/json' });
  const get = (url = `${root}/cta-contact?version=1`, who = 'owner', tenant = 'tenant-a') => fetch(url, { headers: headers(who, tenant) });
  const post = (body: unknown, who = 'owner', tenant = 'tenant-a', url = `${root}/cta-contact`) => fetch(url, { method: 'POST', headers: headers(who, tenant), body: JSON.stringify(body) });
  assert.equal((await fetch(`${root}/cta-contact?version=1`)).status, 401);
  const foreignGet = await get(undefined, 'owner', 'other-tenant');
  assert.equal(foreignGet.status, 404);
  const foreignBody = await foreignGet.json();
  assert.equal(foreignBody.error, 'weekly_cta_package_not_found');
  const wrongPackageGet = await get(`${root.replace(scope.packageId, 'other-package')}/cta-contact?version=1`);
  assert.equal(wrongPackageGet.status, 404);
  assert.deepEqual(await wrongPackageGet.json(), foreignBody, 'foreign tenant must see the same generic absence as a nonexistent package');
  assert.equal((await get(`${root}/cta-contact?version=2`)).status, 409);
  assert.equal((await get(`${root}/cta-contact`)).status, 400);
  const beforeResponse = await get();
  assert.equal(beforeResponse.status, 200);
  assert.equal(beforeResponse.headers.get('cache-control'), 'private, no-store');
  const before = (await beforeResponse.json()).item;
  assert.equal(before.status, 'missing');
  assert.equal(before.selectedProduct, null);
  assert.equal(before.productSelectionStatus, 'unavailable', 'the synthetic 21-name goal no longer matches the enterprise catalogue and must not be projected as a valid choice');
  assert.match(before.frozenCta, /WhatsApp.*free sample/);
  assert.equal((await f.store.list(WEEKLY_CTA_CONTACTS)).totalItems, 0);
  const auditUrl = `${root}/execution-pipeline/task-audit?version=1`;
  const auditBeforeResponse = await get(auditUrl);
  assert.equal(auditBeforeResponse.status, 200, await auditBeforeResponse.clone().text());
  const auditBefore = (await auditBeforeResponse.json()).item;
  assert.equal(auditBefore.items[0]?.ctaContactStatus, 'missing');
  assert.ok(auditBefore.items[0]?.requiredActions.some((a: any) => a.code === 'weekly_cta_contact_required' && a.action === 'cta_contact'));
  const input = { expectedPackageVersion: 1, contactChannel: 'whatsapp', contactValue: '+8619653282176', expectedContextHash: before.contextHash, expectedReceiptId: null };
  assert.equal((await post(input, 'outsider')).status, 403);
  assert.equal((await post(input, 'viewer')).status, 403);
  const foreignPost = await post(input, 'owner', 'other-tenant');
  assert.equal(foreignPost.status, 403);
  const foreignPostBody = await foreignPost.json();
  assert.equal(foreignPostBody.error, 'weekly_cta_actor_forbidden');
  assert.doesNotMatch(JSON.stringify(foreignPostBody), /WhatsApp|free sample|19653282176|product-/i);
  assert.equal((await post({ ...input, samplePromiseConfirmed: true })).status, 400);
  assert.equal((await post({ ...input, expectedContextHash: '0'.repeat(64) })).status, 409);
  assert.equal((await f.store.list(WEEKLY_CTA_CONTACTS)).totalItems, 0);
  const concurrentFirstPosts = await Promise.all([post(input), post(input)]);
  assert.deepEqual(concurrentFirstPosts.map(response => response.status).sort(), [200, 409]);
  assert.equal((await f.store.list(WEEKLY_CTA_CONTACTS)).totalItems, 1, 'concurrent first POSTs must have a single persisted revision');
  const firstResponse = concurrentFirstPosts.find(response => response.status === 200)!;
  assert.equal(firstResponse.status, 200, await firstResponse.clone().text());
  const first = (await firstResponse.json()).item;
  assert.equal(first.status, 'recorded');
  assert.equal(first.contactValue, input.contactValue);
  assert.equal(first.samplePromiseConfirmed, false);
  assert.equal((await post(input)).status, 409);
  const correctionResponse = await post({ ...input, contactValue: '+8619653282177', expectedReceiptId: first.receiptId });
  assert.equal(correctionResponse.status, 200);
  const correction = (await correctionResponse.json()).item;
  assert.notEqual(correction.receiptId, first.receiptId);
  assert.equal((await post({ ...input, contactValue: '+8619653282178', expectedReceiptId: first.receiptId })).status, 409);
  const receipts = await f.store.list<any>(WEEKLY_CTA_CONTACTS);
  assert.deepEqual(receipts.items.map(row => row.revision).sort(), [1, 2]);
  assert.deepEqual(receipts.items.map(row => row.payload.contactValue).sort(), ['+8619653282176', '+8619653282177']);
  assert.ok(receipts.items.every(row => row.payload.samplePromiseConfirmed === false && row.payload.authorizesPublishing === false && row.payload.authorizesCustomerMessages === false));
  const auditAfterResponse = await get(auditUrl);
  assert.equal(auditAfterResponse.status, 200);
  const auditAfter = (await auditAfterResponse.json()).item;
  assert.equal(auditAfter.items[0]?.ctaContactStatus, 'recorded');
  assert.ok(auditAfter.items[0]?.requiredActions.some((a: any) => a.code === 'weekly_cta_sample_evidence_required' && a.action === 'sample_policy'));
  assert.ok(auditAfter.items[0]?.requiredActions.some((a: any) => a.code === 'business_proposition_required'));
  assert.ok(!auditAfter.items[0]?.requiredActions.some((a: any) => a.code === 'weekly_cta_contact_required'));
});

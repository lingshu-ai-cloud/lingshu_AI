import test from 'node:test';
import assert from 'node:assert/strict';
import type { AddressInfo } from 'node:net';
import { mkdtemp, rm } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import express from 'express';
import { auth } from '../storage/index.js';
import { prepareWeeklyEnterpriseFactFixture, reopenWeeklyEnterpriseFactFixtureStore } from '../runtime/weeklyEnterpriseFactSupplement.fixture.js';
import { issueWeeklyPublicationProductSelections, readWeeklyPublicationProductSelectionChoices } from '../socialPrograms/weeklyPublicationProductSelection.js';
import { adoptWeeklyAutomationTemplate } from '../socialPrograms/weeklyAutomationTemplate.js';
import { readWeeklySamplePolicyCandidateContext, readWeeklySamplePolicyEvidence, WEEKLY_SAMPLE_POLICY_CANDIDATES } from '../socialPrograms/weeklySamplePolicyEvidence.js';
import { createSocialProgramsRouter } from './socialPrograms.js';

test('authenticated policy PDF intake stays candidate-only across HTTP, tenant boundary and restart', async t => {
  const root = await mkdtemp(path.join(os.tmpdir(), 'sample-policy-http-'));
  const oldRoot = process.env.LOCAL_OBJECT_STORAGE_ROOT, oldDriver = process.env.OBJECT_STORAGE_DRIVER;
  process.env.LOCAL_OBJECT_STORAGE_ROOT = root; process.env.OBJECT_STORAGE_DRIVER = 'local';
  t.after(async () => {
    if (oldRoot === undefined) delete process.env.LOCAL_OBJECT_STORAGE_ROOT; else process.env.LOCAL_OBJECT_STORAGE_ROOT = oldRoot;
    if (oldDriver === undefined) delete process.env.OBJECT_STORAGE_DRIVER; else process.env.OBJECT_STORAGE_DRIVER = oldDriver;
    await rm(root, { recursive: true, force: true });
  });
  const file = path.join(root, 'store.json');
  const f = await prepareWeeklyEnterpriseFactFixture(t, { persistentFile: file });
  const scope = { tenantId: f.task.tenantId, programId: f.task.programId, packageId: f.task.packageId, packageVersion: 1, publicationTaskId: 'pub' };
  const pkgRow = (await f.store.list<any>('social_weekly_operating_packages')).items[0]!;
  const publication = { ...pkgRow.payload.socialContentPackage.publicationTasks[0], motherContentId: 'mother', status: 'planned' };
  await f.store.update('social_weekly_operating_packages', pkgRow.id, { payload: { ...pkgRow.payload, socialContentPackage: { ...pkgRow.payload.socialContentPackage, publicationTasks: [publication] } } });
  const choices = await readWeeklyPublicationProductSelectionChoices(f.store, scope);
  await issueWeeklyPublicationProductSelections(f.store, scope, 'owner', { expectedContextHash: choices.contextHash, productId: f.profile.products.items![0]!.id!, publicationTaskIds: ['pub'] });
  await adoptWeeklyAutomationTemplate(f.store, scope, 'owner');
  await f.store.create('users', { id: 'outsider', tenantId: 'other-tenant', role: 'admin', active: true });
  await f.store.create('users', { id: 'reader', tenantId: 'tenant-a', role: 'customer_service', active: true });
  t.mock.method(auth, 'verifyToken', async (header: string | undefined) => {
    const matched = /^Bearer (owner|outsider|reader)@(tenant-a|other-tenant)$/.exec(header ?? '');
    return matched ? { userId: matched[1]!, tenantId: matched[2]! } : null;
  });
  const app = express();
  app.use(express.json({ limit: '28mb' }));
  app.use('/api/overseas/social-programs', createSocialProgramsRouter(f.store));
  app.use((error: any, _req: express.Request, res: express.Response, _next: express.NextFunction) => res.status(error.status ?? 500).json({ error: error.code ?? 'internal_error' }));
  const server = app.listen(0, '127.0.0.1');
  await new Promise<void>(resolve => server.once('listening', resolve));
  t.after(() => { server.closeAllConnections(); return new Promise<void>(resolve => server.close(() => resolve())); });
  const url = `http://127.0.0.1:${(server.address() as AddressInfo).port}/api/overseas/social-programs/${scope.programId}/operating-packages/${scope.packageId}/sample-policy-candidates`;
  const headers = (actor = 'owner', tenant = 'tenant-a') => ({ authorization: `Bearer ${actor}@${tenant}`, 'content-type': 'application/json' });
  const get = (actor = 'owner', tenant = 'tenant-a', version = 1) => fetch(`${url}?version=${version}&publicationTaskId=pub`, { headers: headers(actor, tenant) });
  const post = (body: unknown, actor = 'owner', tenant = 'tenant-a') => fetch(url, { method: 'POST', headers: headers(actor, tenant), body: JSON.stringify(body) });
  assert.equal((await fetch(`${url}?version=1&publicationTaskId=pub`)).status, 401);
  assert.equal((await get('owner', 'other-tenant')).status, 404);
  assert.equal((await get('reader')).status, 403);
  assert.equal((await get('owner', 'tenant-a', 2)).status, 409);
  const beforeResponse = await get();
  assert.equal(beforeResponse.status, 200, await beforeResponse.clone().text());
  assert.equal(beforeResponse.headers.get('cache-control'), 'private, no-store');
  const before = (await beforeResponse.json()).item;
  assert.equal(before.policyStatus, 'candidate_only');
  assert.equal(before.selection.productSku, null);
  assert.deepEqual(before.candidates, []);
  const terms = { sampleFeeCny: 0, shippingFeePayer: 'buyer', customsDutyPayer: 'buyer', maximumFreeQuantity: 1, eligibleMarkets: ['CN'], eligibleCustomerTypes: ['business_buyer'], validFrom: '2026-01-01T00:00:00Z', validUntil: '2026-12-31T23:59:59Z' };
  const pdfDataUrl = `data:application/pdf;base64,${Buffer.from('%PDF-1.7\nVerified candidate source\n%%EOF').toString('base64')}`;
  const input = { expectedPackageVersion: 1, publicationTaskId: 'pub', expectedContextHash: before.contextHash, terms, pdfDataUrl };
  assert.equal((await post({ ...input, pdfDataUrl: 'data:text/plain;base64,SGVsbG8=' })).status, 400);
  assert.equal((await post({ ...input, pdfDataUrl: 'data:application/pdf;base64,SGVsbG8=' })).status, 400);
  assert.equal((await post({ ...input, terms: null })).status, 400);
  assert.equal((await post({ ...input, terms: { ...terms, reviewStatus: 'verified' } })).status, 400);
  assert.equal((await post({ ...input, authorizesProduction: true })).status, 400);
  assert.equal((await post({ ...input, expectedContextHash: '0'.repeat(64) })).status, 409);
  assert.equal((await post(input, 'owner', 'other-tenant')).status, 404);
  assert.equal((await post(input, 'reader')).status, 403);
  assert.equal((await f.store.list(WEEKLY_SAMPLE_POLICY_CANDIDATES)).totalItems, 0);
  const savedResponse = await post(input);
  assert.equal(savedResponse.status, 201, await savedResponse.clone().text());
  const saved = (await savedResponse.json()).item;
  assert.equal(saved.policyStatus, 'candidate_only');
  assert.equal(saved.authorizesProduction, false);
  assert.equal(saved.reviewStatus, 'pending_independent_verification');
  assert.ok(!JSON.stringify(saved).includes('sourceKey'));
  assert.equal((await f.store.list(WEEKLY_SAMPLE_POLICY_CANDIDATES)).totalItems, 1);
  const reopened = reopenWeeklyEnterpriseFactFixtureStore(file);
  assert.equal((await readWeeklySamplePolicyCandidateContext(reopened, scope)).candidates[0]?.candidateId, saved.candidateId);
  assert.equal(await readWeeklySamplePolicyEvidence({ store: reopened, scope }), null);
});

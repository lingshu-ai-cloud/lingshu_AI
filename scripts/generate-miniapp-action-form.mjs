import { readFile, writeFile } from 'node:fs/promises';
const source = new URL('../shared/action-form.cjs', import.meta.url);
const target = new URL('../apps/shooting-miniapp/lib/action-form.js', import.meta.url);
const content = '// Generated by scripts/generate-miniapp-action-form.mjs; edit shared/action-form.cjs.\n' + await readFile(source, 'utf8');
const webTarget = new URL('../shared/action-form.mjs', import.meta.url);
const webTypes = new URL('../shared/action-form.d.mts', import.meta.url);
const outputs = [
  [target, content],
  [webTarget, content.replace('module.exports = { normalizeFields, options, fieldValue, buildPayload }', 'export { normalizeFields, options, fieldValue, buildPayload }')],
  [webTypes, '// Generated; edit action-form.d.cts.\n' + await readFile(new URL('../shared/action-form.d.cts', import.meta.url), 'utf8')],
];
for (const [file, value] of outputs) {
  if (process.argv.includes('--check')) {
    if (await readFile(file, 'utf8').catch(() => '') !== value) {
      console.error('Action form is out of date: ' + file.pathname + '. Run node scripts/generate-miniapp-action-form.mjs.');
      process.exitCode = 1;
    }
  } else await writeFile(file, value);
}

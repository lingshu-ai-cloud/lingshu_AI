import { readFile, writeFile } from 'node:fs/promises';
const source = new URL('../shared/request-policy.cjs', import.meta.url);
const target = new URL('../apps/shooting-miniapp/lib/request-policy.js', import.meta.url);
const content = '// Generated by scripts/generate-miniapp-request-policy.mjs; edit shared/request-policy.cjs.\n' + await readFile(source, 'utf8');
const webTarget = new URL('../shared/request-policy.mjs', import.meta.url);
const webTypes = new URL('../shared/request-policy.d.mts', import.meta.url);
const outputs = [
  [target, content],
  [webTarget, content.replace('module.exports = { httpFailure, decisionCommand, terminalReceipt, createRequestGuard }', 'export { httpFailure, decisionCommand, terminalReceipt, createRequestGuard }')],
  [webTypes, '// Generated; edit request-policy.d.cts.\n' + await readFile(new URL('../shared/request-policy.d.cts', import.meta.url), 'utf8')],
];
for (const [file, value] of outputs) {
  if (process.argv.includes('--check')) {
    if (await readFile(file, 'utf8').catch(() => '') !== value) {
      console.error('Request policy is out of date: ' + file.pathname + '. Run node scripts/generate-miniapp-request-policy.mjs.');
      process.exitCode = 1;
    }
  } else await writeFile(file, value);
}

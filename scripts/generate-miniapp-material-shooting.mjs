import { readFile, writeFile } from 'node:fs/promises';
import ts from 'typescript';
// These leaf modules are intentionally platform-free. Never ship browser/server imports into WeChat.
for (const name of ['materialTaxonomy', 'shootingWorkflow', 'shootingReference']) {
  const source = new URL(`../shared/${name}.ts`, import.meta.url);
  const input = await readFile(source, 'utf8');
  const syntax = ts.createSourceFile(source.pathname, input, ts.ScriptTarget.Latest, true);
  if (syntax.statements.some(statement => ts.isImportDeclaration(statement) || (ts.isExportDeclaration(statement) && statement.moduleSpecifier))) throw new Error(`${name} must remain a standalone shared module`);
  const result = ts.transpileModule(input, { compilerOptions: { target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.CommonJS }, reportDiagnostics: true });
  if (result.diagnostics?.some(item => item.category === ts.DiagnosticCategory.Error)) throw new Error(ts.formatDiagnosticsWithColorAndContext(result.diagnostics, { getCanonicalFileName: x => x, getCurrentDirectory: () => '', getNewLine: () => '\n' }));
  const target = new URL(`../apps/shooting-miniapp/lib/${name}.js`, import.meta.url);
  const output = `// Generated by scripts/generate-miniapp-material-shooting.mjs; edit shared/${name}.ts.\n${result.outputText}`;
  if (process.argv.includes('--check')) {
    if (await readFile(target, 'utf8').catch(() => '') !== output) { console.error(`Generated ${name} is stale. Run node scripts/generate-miniapp-material-shooting.mjs.`); process.exitCode = 1; }
  } else await writeFile(target, output);
}

import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const source = new URL('../shared/mobile-domain.mjs', import.meta.url);
const target = new URL('../apps/shooting-miniapp/lib/generated/mobile-domain.js', import.meta.url);
const expected = '// Generated by scripts/sync-mobile-domain.mjs; edit shared/mobile-domain.mjs.\n' + (await readFile(source, 'utf8')).replace('export {', 'module.exports = {');
if (process.argv.includes('--check')) {
  const actual = await readFile(target, 'utf8').catch(() => '');
  if (actual !== expected) { console.error('Shared mobile domain is stale. Run node scripts/sync-mobile-domain.mjs.'); process.exitCode = 1; }
} else {
  await mkdir(fileURLToPath(new URL('.', target)), { recursive: true });
  await writeFile(target, expected);
}

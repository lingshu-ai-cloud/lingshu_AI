def start_module(doc: Document, code: str, title: str, subtitle: str, accent: str = BLUE) -> None:
    # Use page-break-before instead of an inline page-break character. When the
    # preceding table ends exactly at a page boundary, an inline break can move
    # to the next page and create an extra blank page in LibreOffice/Word.
    anchor = doc.add_paragraph()
    anchor.paragraph_format.page_break_before = True
    anchor.paragraph_format.space_after = Pt(0)
    anchor.paragraph_format.line_spacing = Pt(1)
    r = anchor.add_run("\u200b")
    set_run_font(r, size=1, color=WHITE)
    table = doc.add_table(rows=1, cols=2)
    set_table_geometry(table, [1350, 8010], indent=0)
    left, right = table.rows[0].cells
    set_cell_shading(left, accent)
    set_cell_shading(right, NAVY)
    for cell in (left, right):
        set_cell_margins(cell, top=170, bottom=170, start=190, end=190)
        set_cell_border(cell)
    p = left.paragraphs[0]
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run(code)
    set_run_font(r, size=20, bold=True, color=WHITE)
    p = right.paragraphs[0]
    r = p.add_run(title + "\n")
    set_run_font(r, size=17, bold=True, color=WHITE)
    r = p.add_run(subtitle)
    set_run_font(r, size=9.2, color="D6E6FF")
    doc.add_paragraph().paragraph_format.space_after = Pt(1)


def add_action_card(
    doc: Document,
    title: str,
    objective: str,
    owner: str,
    timing: str,
    actions: str,
    evidence: str,
    done: str,
    failure: str,
    accent: str = BLUE,
) -> None:
    table = doc.add_table(rows=1, cols=2)
    set_table_geometry(table, [2050, 7310])
    left, right = table.rows[0].cells
    set_cell_shading(left, accent)
    set_cell_shading(right, LIGHT_BLUE)
    p = left.paragraphs[0]
    r = p.add_run(title)
    set_run_font(r, size=11, bold=True, color=WHITE)
    p = right.paragraphs[0]
    r = p.add_run(objective)
    set_run_font(r, size=10.2, bold=True, color=NAVY)
    rows = [
        ("主责 / 时间", f"{owner}｜{timing}"),
        ("必须做", actions),
        ("必须留证", evidence),
        ("完成标准", done),
        ("未完成处理", failure),
    ]
    for label, value in rows:
        cells = table.add_row().cells
        set_cell_shading(cells[0], PALE_BLUE)
        p = cells[0].paragraphs[0]
        r = p.add_run(label)
        set_run_font(r, size=8.8, bold=True, color=NAVY)
        p = cells[1].paragraphs[0]
        r = p.add_run(value)
        set_run_font(r, size=8.8, color=BLACK)
    set_table_geometry(table, [2050, 7310])
    doc.add_paragraph().paragraph_format.space_after = Pt(2)


